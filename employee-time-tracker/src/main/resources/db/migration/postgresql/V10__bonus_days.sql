-- Dias con bono: un extra fijo por hora trabajada (ej.: food truck + local
-- abiertos a la vez). El admin elige el dia, el monto y quienes lo cobran.
-- No se duplica en feriados: el bono es fijo por hora.
CREATE TABLE bonus_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    bonus_date DATE NOT NULL,
    amount_per_hour DECIMAL(10,2) NOT NULL,
    note VARCHAR(120),
    created_by VARCHAR(255),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_bonus_days_date UNIQUE (bonus_date)
);

CREATE TABLE bonus_day_employees (
    bonus_day_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    PRIMARY KEY (bonus_day_id, employee_id),
    CONSTRAINT fk_bonus_day_employees_day FOREIGN KEY (bonus_day_id) REFERENCES bonus_days (id) ON DELETE CASCADE,
    CONSTRAINT fk_bonus_day_employees_employee FOREIGN KEY (employee_id) REFERENCES employees (id)
);

CREATE INDEX idx_bonus_day_employees_employee ON bonus_day_employees (employee_id);

